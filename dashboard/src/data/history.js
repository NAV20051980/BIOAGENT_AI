// Mock plant-care history log — one timeline per plant, kept as its own
// module separate from `telemetry.js` (live/current reading), `plants.js`
// (identity), and `decisions.js` (current decision logic). This models what
// a future `GET /api/plants/:id/history` response would return: a list of
// past irrigation-relevant events, each capturing the sensor context and the
// AI's action + reasoning at that point in time.
//
// Values are hand-picked mock data, not randomized, so the demo is
// reproducible and each plant's history is consistent with its condition
// profile from telemetry.js/plantHealth.js: plants that read Critical/
// Stressed today show an escalating recent history (monitoring -> watering),
// while Healthy plants show a calmer, mostly "no watering needed" history.
// Entries are ordered most-recent-first, matching how a log is read.

export const HISTORY_EVENT_TYPES = {
  WATERED: 'watered',
  NO_WATERING: 'no_watering',
  MONITORING: 'monitoring',
}

const EVENT_LABELS = {
  [HISTORY_EVENT_TYPES.WATERED]: 'Watering triggered',
  [HISTORY_EVENT_TYPES.NO_WATERING]: 'No watering',
  [HISTORY_EVENT_TYPES.MONITORING]: 'Monitoring',
}

function dayLabel(daysAgo) {
  if (daysAgo === 0) return 'Today'
  if (daysAgo === 1) return 'Yesterday'
  return `${daysAgo} days ago`
}

function makeHistory(plantId, entries) {
  return entries.map((entry, index) => ({
    id: `${plantId}-${index}`,
    label: `${dayLabel(entry.daysAgo)} \u00b7 ${entry.time}`,
    eventLabel: EVENT_LABELS[entry.type],
    ...entry,
  }))
}

